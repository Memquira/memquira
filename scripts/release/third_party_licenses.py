#!/usr/bin/env python3
"""Generate licenses/THIRD_PARTY_LICENSES.txt: the licence texts of the Rust crates linked into the release binaries.

Scope: `memcore-api` (both binaries, `memcore-api` and `memcore-maintenance`) with the release features `qdrant` and
`postgres`, for x86_64-unknown-linux-gnu and x86_64-pc-windows-msvc. A crate is included when it is reachable from
`memcore-api` through normal (not build or dev) dependencies; proc-macro crates and everything reached only through
them run at compile time and are not linked, so they are left out. Workspace crates are memcore's own (LICENSE).

For each crate: name, version, SPDX expression, repository, the targets it links into, and every licence / notice file
the crate ships (LICENSE*, LICENCE*, COPYING*, NOTICE*, UNLICENSE*, COPYRIGHT*), read from the local Cargo registry
sources. Crates that ship no such file are listed at the top with their SPDX expression.

Offline and deterministic (`cargo metadata --offline --locked`; sorted; LF; no timestamps). Usage:
  python3 scripts/release/third_party_licenses.py            # write licenses/THIRD_PARTY_LICENSES.txt
  python3 scripts/release/third_party_licenses.py --check    # exit 1 if the committed file is out of date
"""

from __future__ import annotations

import argparse
import hashlib
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "licenses" / "THIRD_PARTY_LICENSES.txt"
FEATURES = "memcore-api/qdrant,memcore-api/postgres"
TARGETS = ("x86_64-unknown-linux-gnu", "x86_64-pc-windows-msvc")
PREFIXES = ("license", "licence", "copying", "notice", "unlicense", "copyright")


def metadata(target: str) -> dict:
    out = subprocess.run(["cargo", "metadata", "--format-version", "1", "--offline", "--locked", "--features", FEATURES,
                          "--filter-platform", target], cwd=ROOT, capture_output=True, text=True, check=True).stdout
    return json.loads(out)


def linked(meta: dict) -> set[str]:
    pkgs = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    root = next(p["id"] for p in meta["packages"] if p["name"] == "memcore-api" and p["source"] is None)
    seen, stack = set(), [root]
    while stack:
        pid = stack.pop()
        for dep in nodes[pid]["deps"]:
            if not any(k["kind"] is None for k in dep["dep_kinds"]):
                continue
            target = pkgs[dep["pkg"]]
            if any("proc-macro" in t["kind"] for t in target["targets"]):
                continue
            if dep["pkg"] not in seen:
                seen.add(dep["pkg"])
                stack.append(dep["pkg"])
    return {pid for pid in seen if pkgs[pid]["source"] is not None}


def licence_files(manifest: str) -> list[Path]:
    d = Path(manifest).parent
    return sorted((p for p in d.iterdir() if p.is_file() and p.name.lower().startswith(PREFIXES)),
                  key=lambda p: p.name.lower())


def render() -> str:
    lock = (ROOT / "Cargo.lock").read_bytes().replace(b"\r\n", b"\n")
    crates: dict[tuple[str, str], dict] = {}
    for target in TARGETS:
        meta = metadata(target)
        pkgs = {p["id"]: p for p in meta["packages"]}
        for pid in linked(meta):
            p = pkgs[pid]
            c = crates.setdefault((p["name"], p["version"]), {"pkg": p, "targets": set()})
            c["targets"].add("linux" if "linux" in target else "windows")
    keys = sorted(crates, key=lambda k: (k[0].lower(), k[1]))
    without = [k for k in keys if not licence_files(crates[k]["pkg"]["manifest_path"])]
    lines = [
        "memcore - third-party licences of the Rust crates linked into memcore-api and memcore-maintenance",
        "",
        "Generated by scripts/release/third_party_licenses.py (do not edit by hand; regenerate with Cargo.lock).",
        f"Cargo.lock sha256 (LF): {hashlib.sha256(lock).hexdigest()}",
        f"Features: {FEATURES}. Targets: {', '.join(TARGETS)}.",
        "memcore itself is licensed under AGPL-3.0-or-later (LICENSE). The Swagger UI files served at /docs are",
        "Apache-2.0 (swagger-ui/LICENSE, swagger-ui/NOTICE).",
        "",
        f"Crates: {len(keys)}. Crates that ship no licence file (SPDX expression from Cargo.toml applies): {len(without)}",
    ]
    for k in without:
        lines.append(f"  - {k[0]} {k[1]}: {crates[k]['pkg'].get('license') or crates[k]['pkg'].get('license_file') or 'unspecified'}")
    lines += ["", "Index (name version | SPDX | targets):"]
    for k in keys:
        c = crates[k]
        lines.append(f"  {k[0]} {k[1]} | {c['pkg'].get('license') or 'see file'} | {','.join(sorted(c['targets']))}")
    for k in keys:
        c = crates[k]
        p = c["pkg"]
        lines += ["", "=" * 100, f"{k[0]} {k[1]}", f"License: {p.get('license') or 'see file'}",
                  f"Repository: {p.get('repository') or 'n/a'}", f"Linked into: {','.join(sorted(c['targets']))}"]
        for f in licence_files(p["manifest_path"]):
            text = f.read_bytes().replace(b"\r\n", b"\n").decode("utf-8", errors="replace").rstrip("\n")
            lines += ["", f"--- {f.name} ---", text]
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    text = render()
    if ap.parse_args().check:
        current = OUT.read_bytes().decode("utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT.relative_to(ROOT)} is out of date; run scripts/release/third_party_licenses.py", file=sys.stderr)
            return 1
        print(f"{OUT.relative_to(ROOT)} is up to date")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_bytes(text.encode("utf-8"))
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text.encode())} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
